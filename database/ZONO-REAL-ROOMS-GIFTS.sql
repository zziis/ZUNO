create or replace function public.zono_room_is_staff(p_room_id bigint,p_user_id uuid)
returns boolean language sql stable security definer set search_path=public
as $$
  select exists(select 1 from public.zono_rooms r where r.id=p_room_id and r.owner_id=p_user_id)
      or exists(select 1 from public.zono_room_moderators m where m.room_id=p_room_id and m.user_id=p_user_id);
$$;

create or replace function public.zono_room_is_muted(p_room_id bigint,p_user_id uuid)
returns boolean language sql stable security definer set search_path=public
as $$
  select exists(
    select 1 from public.zono_room_restrictions x
    where x.room_id=p_room_id and x.user_id=p_user_id
      and (x.muted_permanent=true or (x.muted_until is not null and x.muted_until>now()))
  );
$$;

-- ---------------------------------------------------------
-- Create room — deduct exactly 30,000 seeds atomically
-- ---------------------------------------------------------
create or replace function public.zono_create_room(p_name text,p_bio text,p_image_url text)
returns jsonb language plpgsql security definer set search_path=public
as $$
declare v_profile public.profiles%rowtype; v_room public.zono_rooms%rowtype;
begin
  if auth.uid() is null then raise exception 'يجب تسجيل الدخول'; end if;
  if length(trim(coalesce(p_name,'')))<2 or length(trim(p_name))>60 then raise exception 'اسم الروم غير صحيح'; end if;
  if length(trim(coalesce(p_bio,'')))<2 or length(trim(p_bio))>240 then raise exception 'نبذة الروم غير صحيحة'; end if;
  if length(trim(coalesce(p_image_url,'')))<8 then raise exception 'صورة الروم مطلوبة'; end if;

  select * into v_profile from public.profiles where id=auth.uid() for update;
  if v_profile.id is null then raise exception 'الحساب غير موجود'; end if;
  if coalesce(v_profile.seeds,0)<30000 then raise exception 'تحتاج 30000 بذرة لإنشاء روم'; end if;

  update public.profiles set seeds=coalesce(seeds,0)-30000 where id=auth.uid();

  insert into public.zono_rooms(owner_id,name,bio,image_url)
  values(auth.uid(),trim(p_name),trim(p_bio),trim(p_image_url))
  returning * into v_room;

  return jsonb_build_object('ok',true,'public_id',v_room.public_id,'room_id',v_room.id);
end $$;
grant execute on function public.zono_create_room(text,text,text) to authenticated;

-- ---------------------------------------------------------
-- Room listing
-- ---------------------------------------------------------
create or replace function public.zono_list_rooms()
returns table(
  public_id bigint,name text,bio text,image_url text,is_locked boolean,
  owner_public_id bigint,owner_name text,active_members bigint,created_at timestamptz
)
language sql security definer set search_path=public
as $$
  select r.public_id,r.name,r.bio,r.image_url,r.is_locked,
         p.public_id,p.display_name,
         (select count(*) from public.zono_room_presence pr
          where pr.room_id=r.id and pr.last_seen_at>now()-interval '45 seconds') as active_members,
         r.created_at
  from public.zono_rooms r
  join public.profiles p on p.id=r.owner_id
  order by r.created_at desc;
$$;
grant execute on function public.zono_list_rooms() to authenticated;

-- ---------------------------------------------------------
-- Enter room
-- ---------------------------------------------------------
create or replace function public.zono_enter_room(p_room_public_id bigint,p_password text default null)
returns jsonb language plpgsql security definer set search_path=public,extensions
as $$
declare v_room public.zono_rooms%rowtype; v_restrict public.zono_room_restrictions%rowtype;
        v_owner boolean; v_mod boolean; v_count bigint;
begin
  if auth.uid() is null then raise exception 'يجب تسجيل الدخول'; end if;

  select * into v_room from public.zono_rooms where public_id=p_room_public_id;
  if v_room.id is null then raise exception 'الروم غير موجود'; end if;

  select * into v_restrict from public.zono_room_restrictions
  where room_id=v_room.id and user_id=auth.uid();

  if coalesce(v_restrict.banned,false) then raise exception 'ROOM_BANNED'; end if;
  if v_restrict.kicked_until is not null and v_restrict.kicked_until>now() then raise exception 'ROOM_KICKED'; end if;

  v_owner := v_room.owner_id=auth.uid();
  v_mod := exists(select 1 from public.zono_room_moderators where room_id=v_room.id and user_id=auth.uid());

  if v_room.is_locked and not(v_owner or v_mod) then
    if p_password is null or p_password='' then raise exception 'ROOM_PASSWORD_REQUIRED'; end if;
    if v_room.password_hash is null
       or extensions.crypt(p_password,v_room.password_hash)<>v_room.password_hash
    then raise exception 'ROOM_PASSWORD_INVALID'; end if;
  end if;

  insert into public.zono_room_presence(room_id,user_id,joined_at,last_seen_at)
  values(v_room.id,auth.uid(),now(),now())
  on conflict(room_id,user_id) do update set last_seen_at=now();

  select count(*) into v_count from public.zono_room_presence
  where room_id=v_room.id and last_seen_at>now()-interval '45 seconds';

  return jsonb_build_object(
    'ok',true,'public_id',v_room.public_id,'name',v_room.name,'bio',v_room.bio,
    'image_url',v_room.image_url,'is_locked',v_room.is_locked,
    'is_owner',v_owner,'is_moderator',v_mod,'active_members',v_count
  );
end $$;
grant execute on function public.zono_enter_room(bigint,text) to authenticated;

create or replace function public.zono_room_heartbeat(p_room_public_id bigint)
returns jsonb language plpgsql security definer set search_path=public
as $$
declare v_room_id bigint; v_x public.zono_room_restrictions%rowtype;
begin
  select id into v_room_id from public.zono_rooms where public_id=p_room_public_id;
  if v_room_id is null then return jsonb_build_object('allowed',false,'reason','تم حذف الروم'); end if;

  select * into v_x from public.zono_room_restrictions where room_id=v_room_id and user_id=auth.uid();
  if coalesce(v_x.banned,false) then return jsonb_build_object('allowed',false,'reason','أنت محظور من هذا الروم'); end if;
  if v_x.kicked_until is not null and v_x.kicked_until>now() then return jsonb_build_object('allowed',false,'reason','تم طردك من الروم'); end if;

  update public.zono_room_presence set last_seen_at=now()
  where room_id=v_room_id and user_id=auth.uid();

  if not found then
    insert into public.zono_room_presence(room_id,user_id) values(v_room_id,auth.uid());
  end if;

  return jsonb_build_object('allowed',true);
end $$;
grant execute on function public.zono_room_heartbeat(bigint) to authenticated;

create or replace function public.zono_leave_room(p_room_public_id bigint)
returns jsonb language plpgsql security definer set search_path=public
as $$
declare v_room_id bigint;
begin
  select id into v_room_id from public.zono_rooms where public_id=p_room_public_id;
  if v_room_id is not null then
    delete from public.zono_room_presence where room_id=v_room_id and user_id=auth.uid();
  end if;
  return jsonb_build_object('ok',true);
end $$;
