create or replace function public.zono_send_room_message(p_room_public_id bigint,p_message text)
returns jsonb language plpgsql security definer set search_path=public
as $$
declare v_room_id bigint; v_x public.zono_room_restrictions%rowtype;
begin
  if auth.uid() is null then raise exception 'يجب تسجيل الدخول'; end if;
  if length(trim(coalesce(p_message,'')))<1 or length(p_message)>1000 then raise exception 'الرسالة غير صالحة'; end if;

  select id into v_room_id from public.zono_rooms where public_id=p_room_public_id;
  if v_room_id is null then raise exception 'الروم غير موجود'; end if;

  if not exists(select 1 from public.zono_room_presence where room_id=v_room_id and user_id=auth.uid() and last_seen_at>now()-interval '2 minutes')
  then raise exception 'يجب دخول الروم أولاً'; end if;

  if public.zono_room_is_muted(v_room_id,auth.uid()) then raise exception 'MUTED'; end if;

  insert into public.zono_room_messages(room_id,sender_id,message_type,content)
  values(v_room_id,auth.uid(),'text',trim(p_message));

  return jsonb_build_object('ok',true);
end $$;
grant execute on function public.zono_send_room_message(bigint,text) to authenticated;

-- ---------------------------------------------------------
-- Active members
-- ---------------------------------------------------------
create or replace function public.zono_room_members(p_room_public_id bigint)
returns table(
  public_id bigint,display_name text,avatar text,is_owner boolean,is_moderator boolean,
  is_muted boolean,is_banned boolean
)
language sql security definer set search_path=public
as $$
  select p.public_id,p.display_name,p.avatar_url,
         (r.owner_id=p.id),
         exists(select 1 from public.zono_room_moderators m where m.room_id=r.id and m.user_id=p.id),
         public.zono_room_is_muted(r.id,p.id),
         coalesce((select x.banned from public.zono_room_restrictions x where x.room_id=r.id and x.user_id=p.id),false)
  from public.zono_rooms r
  join public.zono_room_presence pr on pr.room_id=r.id and pr.last_seen_at>now()-interval '45 seconds'
  join public.profiles p on p.id=pr.user_id
  where r.public_id=p_room_public_id
  order by (r.owner_id=p.id) desc,p.display_name;
$$;
grant execute on function public.zono_room_members(bigint) to authenticated;

-- ---------------------------------------------------------
-- Lock/unlock: owner OR moderator
-- ---------------------------------------------------------
create or replace function public.zono_room_set_lock(p_room_public_id bigint,p_locked boolean,p_password text default null)
returns jsonb language plpgsql security definer set search_path=public,extensions
as $$
declare v_room public.zono_rooms%rowtype;
begin
  select * into v_room from public.zono_rooms where public_id=p_room_public_id;
  if v_room.id is null then raise exception 'الروم غير موجود'; end if;
  if not public.zono_room_is_staff(v_room.id,auth.uid()) then raise exception 'لا تملك صلاحية إدارة الروم'; end if;

  if p_locked then
    if length(coalesce(p_password,''))<4 or length(p_password)>12 then raise exception 'رمز الروم يجب أن يكون من 4 إلى 12 خانة'; end if;
    update public.zono_rooms
    set is_locked=true,password_hash=extensions.crypt(p_password,extensions.gen_salt('bf'))
    where id=v_room.id;
  else
    update public.zono_rooms set is_locked=false,password_hash=null where id=v_room.id;
  end if;

  return jsonb_build_object('ok',true,'is_locked',p_locked);
end $$;
grant execute on function public.zono_room_set_lock(bigint,boolean,text) to authenticated;

-- ---------------------------------------------------------
-- Owner appoints/removes moderators
-- ---------------------------------------------------------
create or replace function public.zono_room_set_moderator(p_room_public_id bigint,p_target_public_id bigint,p_enabled boolean)
returns jsonb language plpgsql security definer set search_path=public
as $$
declare v_room public.zono_rooms%rowtype; v_target uuid;
begin
  select * into v_room from public.zono_rooms where public_id=p_room_public_id;
  if v_room.id is null then raise exception 'الروم غير موجود'; end if;
  if v_room.owner_id<>auth.uid() then raise exception 'هذه الصلاحية لمالك الروم فقط'; end if;

  select id into v_target from public.profiles where public_id=p_target_public_id;
  if v_target is null then raise exception 'المستخدم غير موجود'; end if;
  if v_target=v_room.owner_id then raise exception 'المالك لا يحتاج صلاحية مشرف'; end if;

  if p_enabled then
    insert into public.zono_room_moderators(room_id,user_id) values(v_room.id,v_target)
    on conflict do nothing;
  else
    delete from public.zono_room_moderators where room_id=v_room.id and user_id=v_target;
  end if;

  return jsonb_build_object('ok',true);
end $$;
grant execute on function public.zono_room_set_moderator(bigint,bigint,boolean) to authenticated;

-- ---------------------------------------------------------
-- Moderation: owner or moderators. Cannot moderate owner.
-- clear = remove ban/mute/kick.
-- ---------------------------------------------------------
create or replace function public.zono_room_moderate(
  p_room_public_id bigint,p_target_public_id bigint,p_action text,p_minutes integer default null
)
returns jsonb language plpgsql security definer set search_path=public
as $$
declare v_room public.zono_rooms%rowtype; v_target uuid; v_is_target_mod boolean;
begin
  select * into v_room from public.zono_rooms where public_id=p_room_public_id;
  if v_room.id is null then raise exception 'الروم غير موجود'; end if;
  if not public.zono_room_is_staff(v_room.id,auth.uid()) then raise exception 'لا تملك صلاحية الإدارة'; end if;

  select id into v_target from public.profiles where public_id=p_target_public_id;
  if v_target is null then raise exception 'المستخدم غير موجود'; end if;
  if v_target=v_room.owner_id then raise exception 'لا يمكن اتخاذ إجراء ضد مالك الروم'; end if;

  v_is_target_mod := exists(select 1 from public.zono_room_moderators where room_id=v_room.id and user_id=v_target);
  if v_is_target_mod and v_room.owner_id<>auth.uid() then
    raise exception 'المشرف لا يستطيع اتخاذ إجراء ضد مشرف آخر';
  end if;

  insert into public.zono_room_restrictions(room_id,user_id)
  values(v_room.id,v_target)
  on conflict(room_id,user_id) do nothing;

  if p_action='kick' then
    update public.zono_room_restrictions set kicked_until=now()+interval '15 seconds',updated_at=now()
    where room_id=v_room.id and user_id=v_target;
    delete from public.zono_room_presence where room_id=v_room.id and user_id=v_target;

  elsif p_action='ban' then
    update public.zono_room_restrictions set banned=true,updated_at=now()
    where room_id=v_room.id and user_id=v_target;
    delete from public.zono_room_presence where room_id=v_room.id and user_id=v_target;

  elsif p_action='mute_temp' then
    update public.zono_room_restrictions
    set muted_permanent=false,muted_until=now()+make_interval(mins=>greatest(1,least(coalesce(p_minutes,30),10080))),updated_at=now()
    where room_id=v_room.id and user_id=v_target;

  elsif p_action='mute_perm' then
    update public.zono_room_restrictions set muted_permanent=true,muted_until=null,updated_at=now()
    where room_id=v_room.id and user_id=v_target;

  elsif p_action='clear' then
    update public.zono_room_restrictions
    set banned=false,muted_permanent=false,muted_until=null,kicked_until=null,updated_at=now()
    where room_id=v_room.id and user_id=v_target;

  else raise exception 'إجراء غير معروف';
  end if;

  return jsonb_build_object('ok',true);
end $$;
grant execute on function public.zono_room_moderate(bigint,bigint,text,integer) to authenticated;

