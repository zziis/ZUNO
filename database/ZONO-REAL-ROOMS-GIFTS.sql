-- ---------------------------------------------------------
-- Gifts
-- Rose = 100 feathers per recipient.
-- 20 company / 20 room owner / 60 recipient.
-- To-all charges 100 for every other active member.
-- ---------------------------------------------------------
create or replace function public.zono_send_room_gift(
  p_room_public_id bigint,
  p_recipient_public_id bigint default null,
  p_to_all boolean default false,
  p_gift_key text default 'rose'
)
returns jsonb language plpgsql security definer set search_path=public
as $$
declare
  v_room public.zono_rooms%rowtype;
  v_sender public.profiles%rowtype;
  v_recipient uuid;
  v_recipient_name text;
  v_count integer;
  v_total bigint;
  v_company bigint;
  v_owner bigint;
  v_recipients bigint;
begin
  if auth.uid() is null then raise exception 'يجب تسجيل الدخول'; end if;
  if p_gift_key<>'rose' then raise exception 'هذه الهدية قريبًا'; end if;

  select * into v_room from public.zono_rooms where public_id=p_room_public_id;
  if v_room.id is null then raise exception 'الروم غير موجود'; end if;

  select * into v_sender from public.profiles where id=auth.uid() for update;
  if v_sender.id is null then raise exception 'الحساب غير موجود'; end if;

  if p_to_all then
    select count(*)::integer into v_count
    from public.zono_room_presence pr
    where pr.room_id=v_room.id
      and pr.last_seen_at>now()-interval '45 seconds'
      and pr.user_id<>auth.uid();

    if v_count<1 then raise exception 'لا يوجد مستلمون آخرون في الروم'; end if;
  else
    select p.id,p.display_name into v_recipient,v_recipient_name
    from public.profiles p
    join public.zono_room_presence pr on pr.user_id=p.id
    where p.public_id=p_recipient_public_id
      and pr.room_id=v_room.id
      and pr.last_seen_at>now()-interval '45 seconds';

    if v_recipient is null then raise exception 'المستلم غير موجود في الروم'; end if;
    if v_recipient=auth.uid() then raise exception 'لا يمكنك إرسال هدية لنفسك'; end if;
    v_count:=1;
  end if;

  v_total:=100*v_count;
  if coalesce(v_sender.feathers,0)<v_total then raise exception 'رصيد الريش غير كافٍ'; end if;

  v_company:=20*v_count;
  v_owner:=20*v_count;
  v_recipients:=60*v_count;

  -- sender pays full price
  update public.profiles set feathers=coalesce(feathers,0)-v_total where id=auth.uid();

  -- company 20%
  update public.zono_company_wallet
  set feathers_balance=feathers_balance+v_company,updated_at=now()
  where singleton=true;

  -- room owner 20%
  update public.profiles set feathers=coalesce(feathers,0)+v_owner where id=v_room.owner_id;

  -- recipients 60%
  if p_to_all then
    update public.profiles p
    set feathers=coalesce(p.feathers,0)+60
    where p.id in (
      select pr.user_id from public.zono_room_presence pr
      where pr.room_id=v_room.id
        and pr.last_seen_at>now()-interval '45 seconds'
        and pr.user_id<>auth.uid()
    );
  else
    update public.profiles set feathers=coalesce(feathers,0)+60 where id=v_recipient;
  end if;

  insert into public.zono_room_gifts(
    room_id,sender_id,recipient_id,to_all,gift_key,unit_price,recipient_count,total_cost,
    company_share,owner_share,recipients_share
  ) values(
    v_room.id,auth.uid(),case when p_to_all then null else v_recipient end,p_to_all,'rose',100,v_count,v_total,
    v_company,v_owner,v_recipients
  );

  insert into public.zono_room_messages(room_id,sender_id,message_type,content)
  values(
    v_room.id,auth.uid(),'gift',
    case when p_to_all
      then 'أرسل وردة 🌹 إلى الجميع'
      else 'أرسل وردة 🌹 إلى '||coalesce(v_recipient_name,'المستخدم')
    end
  );

  return jsonb_build_object(
    'ok',true,'recipient_count',v_count,'total_cost',v_total,
    'company_share',v_company,'owner_share',v_owner,'recipients_share',v_recipients
  );
end $$;
