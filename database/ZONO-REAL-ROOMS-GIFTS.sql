-- ZONO REAL ROOMS + MODERATION + GIFTS
-- Run ONCE in Supabase SQL Editor.
-- Room creation: 30,000 seeds.
-- Public room IDs start at 50 and never reuse deleted IDs.
-- Rose gift: 100 feathers. Split = 20% company / 20% room owner / 60% recipient.

create extension if not exists pgcrypto;

-- ---------------------------------------------------------
-- Room IDs start at 50
-- ---------------------------------------------------------
create sequence if not exists public.zono_room_public_id_seq
  as bigint
  start with 50
  increment by 1
  minvalue 50
  no cycle;

create table if not exists public.zono_rooms (
  id bigint generated by default as identity primary key,
  public_id bigint not null unique default nextval('public.zono_room_public_id_seq'),
  owner_id uuid not null references public.profiles(id) on delete cascade,
  name text not null,
  bio text not null,
  image_url text not null,
  is_locked boolean not null default false,
  password_hash text,
  created_at timestamptz not null default now()
);

create table if not exists public.zono_room_moderators (
  room_id bigint not null references public.zono_rooms(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key(room_id,user_id)
);

create table if not exists public.zono_room_restrictions (
  room_id bigint not null references public.zono_rooms(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  banned boolean not null default false,
  muted_permanent boolean not null default false,
  muted_until timestamptz,
  kicked_until timestamptz,
  updated_at timestamptz not null default now(),
  primary key(room_id,user_id)
);

create table if not exists public.zono_room_presence (
  room_id bigint not null references public.zono_rooms(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  joined_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  primary key(room_id,user_id)
);

create table if not exists public.zono_room_messages (
  id bigint generated by default as identity primary key,
  room_id bigint not null references public.zono_rooms(id) on delete cascade,
  sender_id uuid references public.profiles(id) on delete set null,
  message_type text not null default 'text' check(message_type in ('text','gift','system')),
  content text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.zono_room_gifts (
  id bigint generated by default as identity primary key,
  room_id bigint not null references public.zono_rooms(id) on delete cascade,
  sender_id uuid not null references public.profiles(id) on delete cascade,
  recipient_id uuid references public.profiles(id) on delete set null,
  to_all boolean not null default false,
  gift_key text not null,
  unit_price bigint not null,
  recipient_count integer not null,
  total_cost bigint not null,
  company_share bigint not null,
  owner_share bigint not null,
  recipients_share bigint not null,
  created_at timestamptz not null default now()
);

create table if not exists public.zono_company_wallet (
  singleton boolean primary key default true check(singleton),
  feathers_balance bigint not null default 0,
  updated_at timestamptz not null default now()
);
insert into public.zono_company_wallet(singleton,feathers_balance)
values(true,0) on conflict(singleton) do nothing;

