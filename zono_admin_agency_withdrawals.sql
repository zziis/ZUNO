$$;

CREATE OR REPLACE FUNCTION public.zono_agency_review_request(
    p_request_id bigint,
    p_decision text,
    p_new_public_id bigint DEFAULT NULL,
    p_rejection_reason text DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, auth
AS $$
DECLARE
    v_req public.zono_agency_requests%ROWTYPE;
    v_profile public.profiles%ROWTYPE;
    v_decision text := lower(btrim(COALESCE(p_decision,'')));
    v_reason text := NULLIF(btrim(COALESCE(p_rejection_reason,'')),'');
BEGIN
    PERFORM public.zono__require_developer_v2();
    IF v_decision NOT IN ('approved','rejected') THEN RAISE EXCEPTION 'INVALID_DECISION'; END IF;

    SELECT * INTO v_req
    FROM public.zono_agency_requests
    WHERE id = p_request_id
    FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'REQUEST_NOT_FOUND'; END IF;
    IF v_req.status <> 'pending' THEN RAISE EXCEPTION 'REQUEST_NOT_PENDING'; END IF;

    SELECT * INTO v_profile
    FROM public.profiles
    WHERE id = v_req.user_id
    FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'PROFILE_NOT_FOUND'; END IF;

    IF v_decision = 'approved' THEN
        IF p_new_public_id IS NULL OR p_new_public_id < 1 THEN RAISE EXCEPTION 'NEW_PUBLIC_ID_REQUIRED'; END IF;
        IF EXISTS (SELECT 1 FROM public.profiles WHERE public_id=p_new_public_id AND id<>v_profile.id) THEN
            RAISE EXCEPTION 'PUBLIC_ID_IN_USE';
        END IF;

        UPDATE public.profiles
        SET agent_previous_public_id = v_profile.public_id,
            public_id = p_new_public_id,
            role = 'agent',
            agent_verified = true,
            agent_since = now()
        WHERE id = v_profile.id;

        UPDATE public.zono_agency_requests
        SET status='approved', assigned_public_id=p_new_public_id,
            reviewed_by=auth.uid(), reviewed_at=now(), rejection_reason=NULL
        WHERE id=v_req.id;

        INSERT INTO public.zono_notifications(user_id, kind, title, body, sender_public_id, amount, is_read, created_at)
        VALUES (
            v_req.user_id,'agency_status','تم قبول وكالتك',
            'تم اعتماد حسابك كوكيل معتمد ✓. ID الوكيل الجديد: ' || p_new_public_id || '.',
            NULL,v_req.fee_seeds,false,now()
        );

        RETURN jsonb_build_object('ok',true,'status','approved','new_public_id',p_new_public_id);
    ELSE
        IF char_length(COALESCE(v_reason,'')) < 3 THEN RAISE EXCEPTION 'REJECTION_REASON_REQUIRED'; END IF;

        UPDATE public.profiles
        SET seeds = COALESCE(seeds,0) + v_req.fee_seeds
        WHERE id = v_req.user_id;

        UPDATE public.zono_agency_requests
        SET status='rejected', rejection_reason=left(v_reason,300),
            reviewed_by=auth.uid(), reviewed_at=now()
        WHERE id=v_req.id;

        INSERT INTO public.zono_notifications(user_id, kind, title, body, sender_public_id, amount, is_read, created_at)
        VALUES (
            v_req.user_id,'agency_status','تم رفض طلب الوكالة',
            'تم رفض طلب الوكالة. السبب: ' || left(v_reason,300) || '. وتمت إعادة ' || v_req.fee_seeds || ' بذرة إلى حسابك.',
            NULL,v_req.fee_seeds,false,now()
        );

        RETURN jsonb_build_object('ok',true,'status','rejected','refunded_seeds',v_req.fee_seeds);
    END IF;
END;
$$;

