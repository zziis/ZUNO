CREATE OR REPLACE FUNCTION public.zono_agency_pending_requests()
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, auth
AS $$
DECLARE v_result jsonb;
BEGIN
    PERFORM public.zono__require_developer_v2();
    SELECT COALESCE(jsonb_agg(to_jsonb(x) ORDER BY x.created_at ASC),'[]'::jsonb)
    INTO v_result
