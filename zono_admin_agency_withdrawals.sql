-- -------------------------------------------------------------
-- 1) حوالات / سحوبات البذور (V2)
-- -------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.zono_withdrawal_requests_v2 (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    public_id_snapshot bigint NOT NULL,
    display_name_snapshot text,
    method text NOT NULL CHECK (method IN ('fib','qi')),
    account_name text NOT NULL,
    fib_phone text,
    qi_phone_11 text,
    qi_account text,
    amount_seeds bigint NOT NULL CHECK (amount_seeds > 0),
    amount_iqd bigint NOT NULL CHECK (amount_iqd >= 0),
    status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','rejected')),
    rejection_reason text,
    reviewed_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
    reviewed_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS zono_withdrawal_requests_v2_user_idx
    ON public.zono_withdrawal_requests_v2(user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS zono_withdrawal_requests_v2_status_idx
    ON public.zono_withdrawal_requests_v2(status, created_at ASC);

ALTER TABLE public.zono_withdrawal_requests_v2 ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.zono_withdrawal_requests_v2 FROM anon, authenticated;

-- -------------------------------------------------------------
-- 2) طلبات الوكالة
-- -------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.zono_agency_requests (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    public_id_at_request bigint NOT NULL,
    display_name_at_request text,
    fee_seeds bigint NOT NULL DEFAULT 1000 CHECK (fee_seeds > 0),
    status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','rejected')),
    assigned_public_id bigint,
    rejection_reason text,
    reviewed_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
    reviewed_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS zono_agency_requests_user_idx
    ON public.zono_agency_requests(user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS zono_agency_requests_status_idx
    ON public.zono_agency_requests(status, created_at ASC);

ALTER TABLE public.zono_agency_requests ENABLE ROW LEVEL SECURITY;
