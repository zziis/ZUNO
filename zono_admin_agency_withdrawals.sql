CREATE OR REPLACE FUNCTION public.zono_withdrawal_review_v2(
    p_withdrawal_id bigint,
    p_decision text,
    p_rejection_reason text DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, auth
AS $$
DECLARE
    v_req public.zono_withdrawal_requests_v2%ROWTYPE;
    v_decision text := lower(btrim(COALESCE(p_decision,'')));
    v_reason text := NULLIF(btrim(COALESCE(p_rejection_reason,'')),'');
BEGIN
    PERFORM public.zono__require_developer_v2();
    IF v_decision NOT IN ('approved','rejected') THEN RAISE EXCEPTION 'INVALID_DECISION'; END IF;
    IF v_decision = 'rejected' AND char_length(COALESCE(v_reason,'')) < 3 THEN RAISE EXCEPTION 'REJECTION_REASON_REQUIRED'; END IF;

    SELECT * INTO v_req
    FROM public.zono_withdrawal_requests_v2
    WHERE id = p_withdrawal_id
    FOR UPDATE;

    IF NOT FOUND THEN RAISE EXCEPTION 'REQUEST_NOT_FOUND'; END IF;
    IF v_req.status <> 'pending' THEN RAISE EXCEPTION 'REQUEST_NOT_PENDING'; END IF;

    IF v_decision = 'rejected' THEN
        UPDATE public.profiles
        SET seeds = COALESCE(seeds,0) + v_req.amount_seeds
        WHERE id = v_req.user_id;
    END IF;

    UPDATE public.zono_withdrawal_requests_v2
    SET status = v_decision,
        rejection_reason = CASE WHEN v_decision='rejected' THEN left(v_reason,300) ELSE NULL END,
        reviewed_by = auth.uid(),
        reviewed_at = now()
    WHERE id = v_req.id;

    INSERT INTO public.zono_notifications(user_id, kind, title, body, sender_public_id, amount, is_read, created_at)
    VALUES (
        v_req.user_id,
        'withdrawal_status',
        CASE WHEN v_decision='approved' THEN 'تم قبول طلب السحب' ELSE 'تم رفض طلب السحب' END,
        CASE WHEN v_decision='approved'
            THEN 'تم قبول طلب سحب ' || v_req.amount_seeds || ' بذرة.'
            ELSE 'تم رفض طلب السحب. السبب: ' || left(v_reason,300) || '. وتمت إعادة ' || v_req.amount_seeds || ' بذرة إلى حسابك.' END,
        NULL, v_req.amount_seeds, false, now()
    );

    RETURN jsonb_build_object('ok',true,'status',v_decision,'refunded',v_decision='rejected');
END;
$$;

-- -------------------------------------------------------------
-- Agency: user creates request and 1000 seeds are reserved
-- -------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.zono_agency_create_request()
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, auth
AS $$
DECLARE
    v_profile public.profiles%ROWTYPE;
    v_id bigint;
    v_fee bigint := 1000;
BEGIN
    IF auth.uid() IS NULL THEN RAISE EXCEPTION 'NOT_AUTHENTICATED'; END IF;

    SELECT * INTO v_profile
    FROM public.profiles
    WHERE id = auth.uid()
    FOR UPDATE;

    IF NOT FOUND THEN RAISE EXCEPTION 'PROFILE_NOT_FOUND'; END IF;
    IF COALESCE(v_profile.role,'') IN ('agent','developer') THEN RAISE EXCEPTION 'ALREADY_AGENT'; END IF;
    IF EXISTS (SELECT 1 FROM public.zono_agency_requests WHERE user_id=auth.uid() AND status='pending') THEN
        RAISE EXCEPTION 'PENDING_REQUEST_EXISTS';
    END IF;
    IF COALESCE(v_profile.seeds,0) < v_fee THEN RAISE EXCEPTION 'INSUFFICIENT_SEEDS'; END IF;

    UPDATE public.profiles
    SET seeds = COALESCE(seeds,0) - v_fee
    WHERE id = auth.uid();

    INSERT INTO public.zono_agency_requests(user_id, public_id_at_request, display_name_at_request, fee_seeds)
    VALUES (auth.uid(), v_profile.public_id, v_profile.display_name, v_fee)
    RETURNING id INTO v_id;

    INSERT INTO public.zono_notifications(user_id, kind, title, body, sender_public_id, amount, is_read, created_at)
    VALUES (auth.uid(),'agency_status','طلب وكالة قيد المعالجة','تم حجز 1,000 بذرة حتى مراجعة طلب الوكالة.',NULL,v_fee,false,now());

    RETURN jsonb_build_object('ok',true,'id',v_id,'status','pending','fee_seeds',v_fee);
END;
$$;

