CREATE OR REPLACE FUNCTION public.zono__require_developer_v2()
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, auth
AS $$
DECLARE
    v_role text;
BEGIN
    IF auth.uid() IS NULL THEN
        RAISE EXCEPTION 'NOT_AUTHENTICATED';
    END IF;

    SELECT role INTO v_role
    FROM public.profiles
    WHERE id = auth.uid();

    IF COALESCE(v_role,'') <> 'developer' THEN
        RAISE EXCEPTION 'DEVELOPER_ONLY';
    END IF;
END;
$$;

-- -------------------------------------------------------------
-- Withdrawal: create request + deduct seeds immediately
-- -------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.zono_withdrawal_submit_v2(
    p_method text,
    p_account_name text,
    p_fib_phone text,
    p_qi_phone_11 text,
    p_qi_account text,
    p_amount_seeds bigint,
    p_verification_code text
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, auth
AS $$
DECLARE
    v_profile public.profiles%ROWTYPE;
    v_id bigint;
    v_method text := lower(btrim(COALESCE(p_method,'')));
    v_account_name text := btrim(COALESCE(p_account_name,''));
BEGIN
    IF auth.uid() IS NULL THEN RAISE EXCEPTION 'NOT_AUTHENTICATED'; END IF;

    SELECT * INTO v_profile
    FROM public.profiles
    WHERE id = auth.uid()
    FOR UPDATE;

    IF NOT FOUND THEN RAISE EXCEPTION 'PROFILE_NOT_FOUND'; END IF;
    -- جميع المستخدمين المسجلين يمكنهم تقديم طلب سحب؛ صلاحية المطور مطلوبة فقط لمعالجة الطلب.
    IF v_method NOT IN ('fib','qi') THEN RAISE EXCEPTION 'INVALID_METHOD'; END IF;
    IF char_length(v_account_name) < 2 THEN RAISE EXCEPTION 'INVALID_ACCOUNT_NAME'; END IF;
    IF p_amount_seeds IS NULL OR p_amount_seeds < 15000 THEN RAISE EXCEPTION 'MIN_WITHDRAWAL_15000'; END IF;
    IF COALESCE(v_profile.seeds,0) < p_amount_seeds THEN RAISE EXCEPTION 'INSUFFICIENT_SEEDS'; END IF;
    IF char_length(COALESCE(p_verification_code,'')) < 4 OR char_length(COALESCE(p_verification_code,'')) > 8 THEN
        RAISE EXCEPTION 'INVALID_VERIFICATION_CODE';
    END IF;

    IF v_method = 'fib' THEN
        IF char_length(regexp_replace(COALESCE(p_fib_phone,''),'[^0-9]','','g')) < 10 THEN RAISE EXCEPTION 'INVALID_FIB_PHONE'; END IF;
    ELSE
        IF char_length(regexp_replace(COALESCE(p_qi_phone_11,''),'[^0-9]','','g')) <> 11 THEN RAISE EXCEPTION 'INVALID_QI_PHONE'; END IF;
        IF char_length(regexp_replace(COALESCE(p_qi_account,''),'[^0-9]','','g')) < 4 THEN RAISE EXCEPTION 'INVALID_QI_ACCOUNT'; END IF;
    END IF;

    UPDATE public.profiles
    SET seeds = COALESCE(seeds,0) - p_amount_seeds
    WHERE id = auth.uid();

    INSERT INTO public.zono_withdrawal_requests_v2(
        user_id, public_id_snapshot, display_name_snapshot, method, account_name,
        fib_phone, qi_phone_11, qi_account, amount_seeds, amount_iqd
    ) VALUES (
        auth.uid(), v_profile.public_id, v_profile.display_name, v_method, v_account_name,
        NULLIF(btrim(COALESCE(p_fib_phone,'')),''),
        NULLIF(btrim(COALESCE(p_qi_phone_11,'')),''),
        NULLIF(btrim(COALESCE(p_qi_account,'')),''),
        p_amount_seeds, p_amount_seeds
    ) RETURNING id INTO v_id;

    INSERT INTO public.zono_notifications(user_id, kind, title, body, sender_public_id, amount, is_read, created_at)
    VALUES (
        auth.uid(), 'withdrawal_status', 'طلب سحب قيد المعالجة',
        'تم خصم ' || p_amount_seeds || ' بذرة وحجزها حتى مراجعة الإدارة.',
        NULL, p_amount_seeds, false, now()
    );

    RETURN jsonb_build_object('ok',true,'id',v_id,'status','pending','amount_seeds',p_amount_seeds);
END;
$$;

CREATE OR REPLACE FUNCTION public.zono_withdrawal_my_v2()
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, auth
AS $$
DECLARE v_result jsonb;
BEGIN
    IF auth.uid() IS NULL THEN RAISE EXCEPTION 'NOT_AUTHENTICATED'; END IF;
    SELECT COALESCE(jsonb_agg(to_jsonb(x) ORDER BY x.created_at DESC),'[]'::jsonb)
    INTO v_result
    FROM (
        SELECT id, method, amount_seeds, amount_iqd, status, rejection_reason, created_at, reviewed_at
        FROM public.zono_withdrawal_requests_v2
        WHERE user_id = auth.uid()
        ORDER BY created_at DESC
        LIMIT 100
    ) x;
    RETURN v_result;
END;
$$;

